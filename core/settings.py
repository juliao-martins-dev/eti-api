SIMPLE_JWT = {
    # The app refreshes on almost every open anyway -- a teacher punches a few
    # times a day and closes it -- so a short access token costs no round trips
    # the client was not already making, and keeps the window small for a
    # leaked token or a logout that has not taken effect yet.
    'ACCESS_TOKEN_LIFETIME': timedelta(minutes=15),
    # With rotation below, this is an idle timeout, not a re-login deadline: a
    # teacher who punches on any weekday never logs in again, while a device
    # left untouched through the long break has to authenticate once more.
    'REFRESH_TOKEN_LIFETIME': timedelta(days=30),
    # Each refresh returns a new refresh token and blacklists the old one, so a
    # stolen token stops working as soon as the real device refreshes.
    'ROTATE_REFRESH_TOKENS': True,
    'BLACKLIST_AFTER_ROTATION': True,
    'UPDATE_LAST_LOGIN': True,
}

